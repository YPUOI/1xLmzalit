/**
 * Record of all 2026/2027 UEFA Champions League teams keyed by their Arabic name
 */
export const UCL_36_TEAMS: Record<string, Team> = {};

UCL_36_CLUBS_LIST.forEach((club) => {
  UCL_36_TEAMS[club.name] = {
    name: club.name,
    logo: club.logo,
    squad: club.squad
  };
});

/**
 * Helper to retrieve a UCL team by Arabic or English name
 */
export function getUclTeamPreset(nameOrEn: string): UclClubItem | undefined {
  if (!nameOrEn) return undefined;
  const clean = nameOrEn.trim().toLowerCase();
  return UCL_36_CLUBS_LIST.find(
    (c) => c.name.toLowerCase() === clean || c.enName.toLowerCase() === clean
  );
}
